public class LeaveBalance {
    private int userId;
    private String fullName;
    private double daysUsed;
    private double leaveBalance;

    // Getters & Setters
    public int getUserId() { return userId; }
    public void setUserId(int userId) { this.userId = userId; }

    public String getFullname() { return fullName; }
    public void setFullname(String fullname) { this.fullName = fullname; }

    public double getDaysUsed() { return daysUsed; }
    public void setDaysUsed(double daysUsed) { this.daysUsed = daysUsed; }

    public double getLeaveBalance() { return leaveBalance; }
    public void setLeaveBalance(double leaveBalance) { this.leaveBalance = leaveBalance; }
}
